import numpy as np

from lab_config import (FACILITIES, PRESETS, REGIONS, TARGETS, TASK_MODES, TASK_PROFILES,
                        point_in_region, region_for_point)
from planner import Intent, build_problem, intent_from_problem, make_plan, plan_as_text
from robot_sim import HOME_QS, RobotSimulation, waypoints_from_plan


def make_item(preset_name: str, name: str) -> dict:
    preset = PRESETS[preset_name]
    x, y = REGIONS[preset["region"]]["xy"]
    return {"name": name, "label": preset_name, "preset": preset_name, "kind": preset["kind"],
            "size": preset["size"], "rgba": preset["rgba"],
            "position": (x, y, 0.07 + preset["size"][2] + 0.002), "location": preset["region"]}


fuse = make_item("熔断器", "faulty_fuse_1")
problem = build_problem([fuse], Intent(fuse["name"], "fuse_slot"))
assert intent_from_problem(problem, [fuse], TARGETS) == Intent(fuse["name"], "fuse_slot")
assert "left_arm right_arm - arm" in problem
assert "_arm" in plan_as_text(make_plan([fuse], Intent(fuse["name"], "fuse_slot")))

# A single-arm task must honor either explicit arm selection.
for selected_arm in HOME_QS:
    fuse_plan = make_plan([fuse], Intent(fuse["name"], "fuse_slot"), selected_arm)
    assert {step["args"][0] for step in fuse_plan} == {selected_arm}
    assert [step["action"] for step in fuse_plan][:3] == ["pick", "stage-component", "insert-component"]

sim = RobotSimulation([fuse])
assert sim.model.nu == 12
assert sim.render({"azimuth": 90, "elevation": -45, "distance": 1.6,
                   "lookat": [0.45, 0.0, 0.2]}).shape == (520, 800, 3)
for arm in HOME_QS:
    assert sim.arm_q(arm).shape == (6,)
    assert sim.ee_position(arm).shape == (3,)

# Object free joints must never appear as autogenerated robot labels such as
# "joint12"; a task-focused scene should contain only its relevant fixture.
focused_sim = RobotSimulation([fuse], active_facility="fuse_slot")
object_joint = focused_sim.model.joint(f"obj_{fuse['name']}_free").id
assert focused_sim.model.jnt_group[object_joint] == 3
fixture_bodies = [focused_sim.model.body(i).name for i in range(focused_sim.model.nbody)
                  if (focused_sim.model.body(i).name or "").startswith("fixture_")]
assert fixture_bodies == ["fixture_fuse_slot"], fixture_bodies

shield = make_item("绝缘护罩", "shield_1")
shield_plan = make_plan([shield], Intent(shield["name"], "cover_area"))
shield_actions = [step["action"] for step in shield_plan]
assert shield_actions[:5] == ["pick", "stage-component", "stabilize-fixture", "assisted-cover", "release-fixture"]
shield_waypoints = waypoints_from_plan(shield_plan, [shield], TARGETS)
shield_sim = RobotSimulation([shield], active_facility="cover_area")
shield_q = {arm: q.copy() for arm, q in HOME_QS.items()}
shield_assistant = shield_plan[2]["args"][0]
assistant_hold_q = None
for waypoint in shield_waypoints:
    arm = waypoint.arm
    other = "right_arm" if arm == "left_arm" else "left_arm"
    target_q = (waypoint.joint_target.copy() if waypoint.joint_target is not None else
                shield_sim.solve_ik(waypoint.position, shield_q[arm], arm, shield_q[other]))
    for q in shield_sim.interpolate(shield_q[arm], target_q, 20):
        shield_issues = shield_sim.validate_q(q, arm, shield_q[other])
        assert not shield_issues, f"{waypoint.label}: {shield_issues}"
        shield_sim.step_to(q, arm)
        if waypoint.pddl_action.startswith("assisted-cover("):
            assert assistant_hold_q is not None
            assert np.linalg.norm(shield_sim.arm_q(shield_assistant) - assistant_hold_q) < 1e-8
    shield_q[arm] = target_q
    if waypoint.pddl_action.startswith("stabilize-fixture(") and waypoint.grip:
        assistant_hold_q = target_q.copy()
for region_name, region in REGIONS.items():
    x, y = region["xy"]
    assert point_in_region(x, y, region_name)
    assert region_for_point(x, y) == region_name
    assert TARGETS[region_name][:2] == region["xy"]

# The wire task must visibly use both arms and the new actions.
wire = make_item("待接导线", "wire_1")
wire_plan = make_plan([wire], Intent("wire_1", "terminal_slot"))
wire_text = plan_as_text(wire_plan)
assert "left_arm" in wire_text and "right_arm" in wire_text
assert "strip-wire" in wire_text and "insert-wire" in wire_text
wire_waypoints = waypoints_from_plan(wire_plan, [wire], TARGETS)
assert {w.arm for w in wire_waypoints} == {"left_arm", "right_arm"}

# Execute the collaboration semantics, not just isolated IK targets.  During
# right-arm stripping, the left arm must remain fixed with the wire attached;
# the wrists must be near enough to express cooperation without intersecting.
wire_sim = RobotSimulation([wire])
wire_q = {arm: q.copy() for arm, q in HOME_QS.items()}
left_hold_position = None
strip_distances = []
for index, waypoint in enumerate(wire_waypoints):
    arm = waypoint.arm
    other = "right_arm" if arm == "left_arm" else "left_arm"
    target_q = (waypoint.joint_target.copy() if waypoint.joint_target is not None else
                wire_sim.solve_ik(waypoint.position, wire_q[arm], arm, wire_q[other]))
    for q in wire_sim.interpolate(wire_q[arm], target_q, 24):
        issues = wire_sim.validate_q(q, arm, wire_q[other])
        assert not issues, f"wire collaboration step {index + 1}: {issues}"
        wire_sim.step_to(q, arm)
        if waypoint.pddl_action.startswith("strip-wire("):
            assert left_hold_position is not None
            assert np.linalg.norm(wire_sim.ee_position("left_arm") - left_hold_position) < 1e-8
            wire_adr = wire_sim.object_qadr[wire["name"]]
            expected_wire = wire_sim.ee_position("left_arm") + np.array([0, 0, -0.08])
            assert np.linalg.norm(wire_sim.data.qpos[wire_adr:wire_adr + 3] - expected_wire) < 1e-8
    if (waypoint.pddl_action.startswith(("pick(", "assisted-pick("))
            and waypoint.grip and wire_sim.grabbed[arm] is None):
        wire_sim.set_grab(wire["name"], arm)
    if waypoint.pddl_action.startswith("hold-wire(") and waypoint.label.startswith("左臂稳定"):
        left_hold_position = wire_sim.ee_position("left_arm").copy()
    if waypoint.pddl_action.startswith("strip-wire(") and waypoint.label.startswith("闭合"):
        strip_distances.append(np.linalg.norm(wire_sim.ee_position("left_arm") -
                                              wire_sim.ee_position("right_arm")))
    if waypoint.pddl_action.startswith("place(") and not waypoint.grip:
        wire_sim.set_grab(None, arm)
    wire_q[arm] = target_q
assert strip_distances and 0.14 <= strip_distances[0] <= 0.21, strip_distances
wire_adr = wire_sim.object_qadr[wire["name"]]
wire_final = wire_sim.data.qpos[wire_adr:wire_adr + 3]
expected_final = np.array([TARGETS["terminal_slot"][0], TARGETS["terminal_slot"][1],
                           0.07 + wire["size"][2]])
assert np.linalg.norm(wire_final - expected_final) < 0.015, (wire_final, expected_final)

